import type { ProjectKey } from './projects'

export interface EvidenceItem {
  src: string
  alt: string
  caption: string
  layout?: 'wide' | 'compact'
}

export interface RecordLink {
  label: string
  href: string
}

export interface ResultRow {
  item: string
  value: string
  /** 조건(표본·측정 횟수·개발 중 값 여부). 조건 없는 숫자는 올리지 않는다. */
  cond: string
}

export interface Decision {
  title: string
  body: string
  image?: EvidenceItem
  record?: RecordLink
}

export interface Check {
  title: string
  /** 찾은 것 → 원인 → 바꾼 것과 결과. 첫 문장만 접힌 상태로 보인다. */
  body: string
  image?: EvidenceItem
  record?: RecordLink
}

export interface Track {
  problem?: { body: string; source?: string; image?: EvidenceItem }
  structure?: { body: string; image?: EvidenceItem; gallery?: EvidenceItem[] }
  results?: {
    rows: ResultRow[]
    /** 열 이름(기본: 항목 · 값 · 조건) */
    columns?: [string, string, string]
    note?: string
    repo?: RecordLink
    image?: EvidenceItem
  }
  decisions?: Decision[]
  checks?: Check[]
  gallery?: { label: string; items: EvidenceItem[] }
}

export interface RoomData {
  key: ProjectKey
  /** 기준 시점 칩 */
  asOf: string
  summary: {
    role: string
    results: { value: string; label: string; cond: string }[]
    tech: string[]
  }
  mainImage: EvidenceItem
  /** 음성 연구 전용: 과제와 내 자리 */
  context?: {
    body: string
    image?: EvidenceItem
    periods?: { label: string; period: string; note?: string }[]
  }
  tracks: { id: string; label: string; period?: string; track: Track }[]
  delegation?: {
    delegated: string
    did: string
    verify: string
    fixed: string
    caseLabel: string
    caseLine: string
    methods?: { method: string; where: string }[]
  }
  limits: { title: string; body: string }[]
  links: { label: string; href?: string; note?: string }[]
  /** 인용 표기(논문) */
  citation?: string
}

